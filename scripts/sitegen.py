#!/usr/bin/env python3
"""Site tooling for SpecItOut documentation sites (process rev 9, P53-P56). Standard library only.

    python3 scripts/sitegen.py nav        # write mkdocs.yml nav from page id/parent/order
    python3 scripts/sitegen.py generate   # fill <!-- generated:NAME --> ... <!-- /generated --> blocks
    python3 scripts/sitegen.py check      # validate the site; exit 1 on any error

Options: --site definition|implementation (default: from .specitout/sdd.json kind),
         --code-root PATH (implementation sites: the code checkout that Where tables point into).
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
MKDOCS = ROOT / "mkdocs.yml"

STATUSES = {"draft", "approved", "superseded"}
TYPES = {"overview", "index", "feature", "design", "requirement", "architecture", "reference", "record"}
LEVELS = {"unit", "integration", "ui", "manual", "measurement"}
VAGUE = re.compile(r"\b(valid|correctly|as expected|appropriate|works|etc\.)", re.I)
SEMVER = re.compile(r"^\d+\.\d+\.\d+$")
GEN = re.compile(r"(<!-- generated:([a-z-]+) -->\n)(.*?)(<!-- /generated -->)", re.S)
REQ_HEAD = re.compile(r"^### (R-[A-Z]+-\d{3}) — (.+)$", re.M)
CASE_HEAD = re.compile(r"^#### (R-[A-Z]+-\d{3}\.T\d+) — Scenario: (.+)$", re.M)
AC_LINE = re.compile(r"^- \*\*(F-\d+\.AC-\d+)\*\*", re.M)
ID_REF = re.compile(r"\b(?:F-\d+(?:\.(?:CR|AC)-\d+)?|UC-[A-Z]+-\d+|SCR-[A-Z]+-\d+|FLW-[A-Z]+-\d+|"
                    r"ADR-\d+|DEC-\d+|COR-\d+|SRC-\d+|ING-\d+|PER-\d+|R-[A-Z]+-\d{3}(?:\.T\d+)?)\b")
NAV_MARK = "# --- nav: generated by scripts/sitegen.py nav; edit page front matter, not this list ---"


@dataclass
class Page:
    path: Path
    rel: str
    meta: dict
    body: str
    children: list = field(default_factory=list)

    @property
    def id(self) -> str:
        return self.meta.get("id", "")

    @property
    def version(self) -> str:
        return self.meta.get("spec_version") or self.meta.get("def_version") or ""

    def text(self) -> str:
        return self.path.read_text()


def parse_front_matter(text: str) -> tuple[dict, str]:
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 4)
    if end < 0:
        return {}, text
    meta = {}
    for line in text[4:end].splitlines():
        if ":" in line and not line.startswith("#"):
            k, v = line.split(":", 1)
            meta[k.strip()] = v.split(" #")[0].strip().strip('"')
    return meta, text[end + 5:]


def load_pages() -> list[Page]:
    pages = []
    for p in sorted(DOCS.rglob("*.md")):
        meta, body = parse_front_matter(p.read_text())
        pages.append(Page(p, p.relative_to(DOCS).as_posix(), meta, body))
    by_id = {pg.id: pg for pg in pages if pg.id}
    for pg in pages:
        parent = by_id.get(pg.meta.get("parent", ""))
        if parent:
            parent.children.append(pg)
    for pg in pages:
        pg.children.sort(key=lambda c: (float(c.meta.get("order", 999)), c.id))
    return pages


def site_kind(args) -> str:
    if args.site:
        return args.site
    try:
        kind = json.loads((ROOT / ".specitout" / "sdd.json").read_text()).get("kind", "")
    except FileNotFoundError:
        return "implementation"  # the docs branch carries no manifest (P48)
    return "implementation" if "implementation" in str(kind) else "definition"


def anchor(heading: str) -> str:
    """MkDocs' default toc slug for a heading: `R-CMUSE-004 — A call…` -> `r-cmuse-004-a-call`."""
    s = re.sub(r"[^\w\s-]", "", heading).strip().lower()
    return re.sub(r"[-\s]+", "-", s)


def link(frm: Page, to: Page) -> str:
    return os.path.relpath(to.rel, os.path.dirname(frm.rel) or ".").replace(os.sep, "/")


def strip_generated(text: str) -> str:
    """Drop generated content and fenced code, so examples and tables are never parsed as definitions."""
    text = GEN.sub(lambda m: m.group(1) + m.group(4), text)
    return re.sub(r"^(```|~~~).*?^\1[^\n]*$", "", text, flags=re.M | re.S)


def section(text: str, start: str) -> str:
    """Body of the markdown section whose heading line starts with `start`."""
    m = re.search(rf"^{re.escape(start)}.*$", text, re.M)
    if not m:
        return ""
    level = len(start) - len(start.lstrip("#"))
    rest = text[m.end():]
    stop = re.search(rf"^#{{1,{level}}} ", rest, re.M)
    return rest[: stop.start()] if stop else rest


# ---------------------------------------------------------------- generators

def requirement_blocks(page: Page):
    body = strip_generated(page.body)
    heads = list(REQ_HEAD.finditer(body))
    for i, m in enumerate(heads):
        end = heads[i + 1].start() if i + 1 < len(heads) else len(body)
        block = body[m.start():end]
        block = re.split(r"^## ", block, flags=re.M)[0]
        yield m.group(1), m.group(2).strip(), block


def field_line(block: str, name: str) -> str:
    m = re.search(rf"^\*\*{name}\.\*\* *(.+)$", block, re.M)
    return m.group(1).strip() if m else ""


def gen_children(page: Page, pages, by_id) -> str:
    rows = ["| ID | Title | Status |", "|---|---|---|"]
    for c in page.children:
        rows.append(f"| {c.id} | [{c.meta.get('title', c.id)}]({link(page, c)}) | {c.meta.get('status', '')} |")
    return "\n".join(rows) + "\n"


def gen_requirements(page: Page, pages, by_id) -> str:
    rows = ["| ID | Title | Page | Source |", "|---|---|---|---|"]
    for c in page.children:
        for rid, title, block in requirement_blocks(c):
            rows.append(f"| {rid} | {title} | [{c.id}]({link(page, c)}#{anchor(rid + ' — ' + title)}) | {field_line(block, 'Source')} |")
    return "\n".join(rows) + "\n"


def feature_change_of(ref: str) -> str:
    ref = ref.split("@")[0]
    m = re.match(r"(F-\d+(?:\.CR-\d+)?)", ref)
    return m.group(1) if m else ""


def gen_fmap(page: Page, pages, by_id) -> str:
    serving: dict[str, list] = {}
    versions: dict[str, set] = {}
    for pg in pages:
        if pg.meta.get("type") != "requirement":
            continue
        for rid, title, block in requirement_blocks(pg):
            for ref in re.split(r"[,;] *", field_line(block, "Source")):
                fc = feature_change_of(ref.strip())
                if fc and rid not in (r for r, *_ in serving.get(fc, [])):
                    serving.setdefault(fc, []).append((rid, pg, anchor(f"{rid} — {title}")))
                    if "@" in ref:
                        versions.setdefault(fc, set()).add(ref.split("@")[1].strip())
    designs = design_index(pages)
    def key(fc):
        n = re.findall(r"\d+", fc)
        return [int(x) for x in n]
    rows = ["| Feature change | Requirements | Designs | Definition version |", "|---|---|---|---|"]
    for fc in sorted(serving, key=key):
        reqs = ", ".join(f"[{r}]({link(page, pg)}#{a})" for r, pg, a in serving[fc])
        ds = ", ".join(d.id for d in designs.get(fc.split(".")[0], []) if fc in d.meta.get("_serves", "") or "." not in fc)
        rows.append(f"| {fc} | {reqs} | {ds or '—'} | {', '.join(sorted(versions.get(fc, {'—'})))} |")
    return "\n".join(rows) + "\n"


def design_index(pages) -> dict[str, list]:
    out: dict[str, list] = {}
    for pg in pages:
        if pg.meta.get("type") != "design":
            continue
        serves = field_line(strip_generated(pg.body), "Serves")
        pg.meta["_serves"] = serves
        for f in set(re.findall(r"\bF-\d+\b", serves)):
            out.setdefault(f, []).append(pg)
    return out


def gen_designs(page: Page, pages, by_id) -> str:
    rows = ["| ID | Title | Serves |", "|---|---|---|"]
    for d in sorted(design_index(pages).get(page.id, []), key=lambda d: d.id):
        rows.append(f"| {d.id} | [{d.meta.get('title')}]({link(page, d)}) | {d.meta['_serves']} |")
    return "\n".join(rows) + "\n"


def acceptance_criteria(page: Page) -> tuple[list[str], dict[str, str]]:
    body = strip_generated(page.body)
    acs = AC_LINE.findall(body)
    superseded = {}
    for m in re.finditer(r"^## (F-\d+\.CR-\d+)", body, re.M):
        # The PDF template puts **Supersedes.** on the **Kind.** line (p49), so search the whole line.
        for line in re.findall(r"\*\*Supersedes\.\*\*([^\n]*)", section(body, f"## {m.group(1)}")):
            for ac in re.findall(r"F-\d+\.AC-\d+", line):
                superseded[ac] = m.group(1)
    return acs, superseded


def gen_effective_ac(page: Page, pages, by_id) -> str:
    acs, sup = acceptance_criteria(page)
    eff = [a for a in acs if a not in sup]
    lines = [" · ".join(eff)]
    for a, cr in sup.items():
        lines.append(f"({a} superseded by {cr})")
    return "\n".join(lines) + "\n"


def gen_families(page: Page, pages, by_id) -> str:
    feat = by_id.get("FEAT")
    rows = ["| Family | Features | Status |", "|---|---|---|"]
    for fam in (feat.children if feat else []):
        fs = ", ".join(f"[{f.id}]({link(page, f)}) {f.meta.get('title')}" for f in fam.children)
        rows.append(f"| [{fam.id} — {fam.meta.get('title')}]({link(page, fam)}) | {fs} | {fam.meta.get('status')} |")
    return "\n".join(rows) + "\n"


def gen_features(page: Page, pages, by_id) -> str:
    rows = ["| Feature | Family | Changes built | Status |", "|---|---|---|---|"]
    feats = [p for p in pages if p.meta.get("type") == "feature"]
    for f in sorted(feats, key=lambda p: int(re.findall(r"\d+", p.id)[0])):
        changes = re.findall(r"^## (F-\d+(?:\.CR-\d+)?|COR-\d+)\b", f.body, re.M)
        rows.append(f"| [{f.id} {f.meta.get('title')}]({link(page, f)}) | {f.rel.split('/')[1].upper()} | "
                    f"{', '.join(changes)} | {f.meta.get('status')} |")
    return "\n".join(rows) + "\n"


WHERE_ROW = re.compile(r"^\| *(R-[A-Z]+-\d{3}) *\| *`([^`]+)` *\| *(.+?) *\|$", re.M)


def where_rows(page: Page):
    for m in re.finditer(r"^### Where\s*$", page.body, re.M):
        chunk = page.body[m.end():]
        stop = re.search(r"^#{1,3} ", chunk, re.M)
        for r in WHERE_ROW.finditer(chunk[: stop.start()] if stop else chunk):
            yield r.group(1), r.group(2), [s.strip(" `") for s in r.group(3).split(",")]


def gen_code_map(page: Page, pages, by_id) -> str:
    files: dict[str, dict] = {}
    for f in pages:
        if f.meta.get("type") != "feature":
            continue
        for rid, path, syms in where_rows(f):
            e = files.setdefault(path, {"reqs": set(), "feats": set(), "syms": set()})
            e["reqs"].add(rid); e["feats"].add(f.id); e["syms"].update(s for s in syms if s)
    rows = ["| Module | Symbols | Requirements | Features |", "|---|---|---|---|"]
    for path in sorted(files):
        e = files[path]
        rows.append(f"| `{path}` | {', '.join(sorted(e['syms']))} | {', '.join(sorted(e['reqs']))} | "
                    f"{', '.join(sorted(e['feats'], key=lambda x: int(x[2:])))} |")
    return "\n".join(rows) + "\n"


GENERATORS = {"children": gen_children, "requirements": gen_requirements, "fmap": gen_fmap,
              "designs": gen_designs, "effective-ac": gen_effective_ac, "families": gen_families,
              "features": gen_features, "code-map": gen_code_map}


def regenerate(pages) -> dict[Path, str]:
    by_id = {p.id: p for p in pages}
    out = {}
    for pg in pages:
        text = pg.text()
        def fill(m):
            gen = GENERATORS.get(m.group(2))
            return m.group(1) + (gen(pg, pages, by_id) if gen else m.group(3)) + m.group(4)
        new = GEN.sub(fill, text)
        if new != text:
            out[pg.path] = new
    return out


# ---------------------------------------------------------------- nav

def nav_lines(pages) -> list[str]:
    by_id = {p.id: p for p in pages}
    home = by_id.get("HOME")
    lines = ["nav:", f'  - "Home": {home.rel}']
    def title(p):
        return f'"{p.id} {p.meta.get("title", "")}"' if p.id != "HOME" else '"Home"'
    def emit(p, depth):
        ind = "  " * (depth + 1)
        if p.children:
            lines.append(f"{ind}- {title(p)}:")
            lines.append(f"{ind}    - {p.rel}")
            for c in p.children:
                emit(c, depth + 2)
        else:
            lines.append(f"{ind}- {title(p)}: {p.rel}")
    for c in home.children:
        emit(c, 0)
    return lines


def write_nav(pages):
    text = MKDOCS.read_text()
    head = text.split(NAV_MARK)[0].rstrip() + "\n\n"
    MKDOCS.write_text(head + NAV_MARK + "\n" + "\n".join(nav_lines(pages)) + "\n")


# ---------------------------------------------------------------- check

class Report:
    def __init__(self):
        self.errors, self.warnings = [], []
    def err(self, where, msg): self.errors.append(f"{where}: {msg}")
    def warn(self, where, msg): self.warnings.append(f"{where}: {msg}")


def check(pages, kind: str, code_root: Path | None) -> Report:
    r = Report()
    by_id: dict[str, Page] = {}
    for p in pages:
        m = p.meta
        for key in ("id", "parent", "order", "type", "title", "status", "updated"):
            if key not in m and not (key == "parent" and m.get("id") == "HOME"):
                r.err(p.rel, f"front matter lacks `{key}`")
        if kind == "definition":
            in_spec, in_meta = p.rel.startswith("spec/"), p.rel.startswith("meta/")
            need = ["spec_version"] if in_spec else ["def_version", "spec_version"] if in_meta else ["def_version"]
        else:
            need = ["spec_version"]
        for key in need:
            if not SEMVER.match(m.get(key, "")):
                r.err(p.rel, f"`{key}` missing or not semver")
        if m.get("status") not in STATUSES:
            r.err(p.rel, f"status `{m.get('status')}` not in {sorted(STATUSES)}")
        if m.get("type") not in TYPES:
            r.err(p.rel, f"type `{m.get('type')}` not in {sorted(TYPES)}")
        if not re.match(r"^\d{4}-\d{2}-\d{2}$", m.get("updated", "")):
            r.err(p.rel, "`updated` is not an ISO date")
        if p.id in by_id:
            r.err(p.rel, f"duplicate page id {p.id} (also {by_id[p.id].rel})")
        by_id[p.id] = p

    # hierarchy: parents exist, every page reachable from HOME, depth <= 3 below home
    seen = set()
    def walk(p, depth):
        seen.add(p.id)
        if depth > 3:
            r.warn(p.rel, f"nav depth {depth} below home exceeds 3 (P53)")
        for c in p.children:
            walk(c, depth + 1)
    if "HOME" not in by_id:
        r.err("index.md", "no HOME page")
    else:
        walk(by_id["HOME"], 0)
    for p in pages:
        if p.id and p.id not in seen:
            r.err(p.rel, f"orphan: parent `{p.meta.get('parent')}` does not lead to HOME")

    # revision history on every page; newest row equals page version
    for p in pages:
        hist = section(p.body, "## Revision history")
        rows = re.findall(r"^\| *(\d+\.\d+\.\d+) *\|", hist, re.M)
        if not rows:
            r.err(p.rel, "no `## Revision history` table")
            continue
        versions = [tuple(map(int, v.split("."))) for v in rows]
        if versions != sorted(versions, reverse=True):
            r.err(p.rel, "revision history is not newest first")
        page_v = p.meta.get("spec_version") if kind != "definition" or p.rel.startswith(("spec/",)) else \
            p.meta.get("def_version")
        if p.rel.startswith("meta/") and kind == "definition":
            page_v = max(p.meta.get("def_version", "0.0.0"), p.meta.get("spec_version", "0.0.0"),
                         key=lambda v: tuple(map(int, v.split("."))))
        if page_v and rows[0] != page_v:
            r.err(p.rel, f"newest revision {rows[0]} != page version {page_v}")

    # budget (P53/P55): warn above 300 lines or 12 requirements
    for p in pages:
        n = p.text().count("\n")
        reqs = len(REQ_HEAD.findall(strip_generated(p.body)))
        if n > 300:
            r.warn(p.rel, f"{n} lines exceeds the 300-line budget")
        if reqs > 12:
            r.warn(p.rel, f"{reqs} requirements exceeds 12 per page")

    # known IDs: pages, acceptance criteria, change requests, requirements, test cases
    known = set(by_id)
    for p in pages:
        body = strip_generated(p.body)
        known.update(AC_LINE.findall(body))
        known.update(re.findall(r"^## (F-\d+\.CR-\d+)", body, re.M))
        known.update(re.findall(r"^### (R-[A-Z]+-\d{3})", body, re.M))
        known.update(re.findall(r"^#### (R-[A-Z]+-\d{3}\.T\d+)", body, re.M))
        known.update(re.findall(r"^### (UC-[A-Z]+-\d+|SCR-[A-Z]+-\d+|FLW-[A-Z]+-\d+)", body, re.M))
    if kind == "implementation":
        known_ext = None  # implementation sites cite upstream IDs; resolved by sio reconcile, not here
    else:
        known_ext = known

    # requirement blocks
    req_ids = set()
    for p in pages:
        for rid, title, block in requirement_blocks(p):
            if rid in req_ids:
                r.err(p.rel, f"duplicate requirement {rid}")
            req_ids.add(rid)
            if p.meta.get("type") != "requirement":
                r.err(p.rel, f"{rid} on a page whose type is not `requirement`")
            for f in ("Requirement", "Rationale", "Source", "Revisions"):
                if not field_line(block, f):
                    r.err(p.rel, f"{rid} lacks **{f}.**")
            if not re.search(r"\b(MUST|SHALL|MUST NOT|SHOULD)\b", field_line(block, "Requirement")
                             + block.split("**Rationale.**")[0]):
                r.err(p.rel, f"{rid} Requirement has no RFC 2119 keyword")
            cases = list(CASE_HEAD.finditer(block))
            if not cases:
                r.err(p.rel, f"{rid} has no test case (#### {rid}.T1 — Scenario: …)")
            for i, c in enumerate(cases):
                if not c.group(1).startswith(rid + ".T"):
                    r.err(p.rel, f"test case {c.group(1)} is not numbered under {rid}")
                end = cases[i + 1].start() if i + 1 < len(cases) else len(block)
                cb = block[c.end():end]
                lvl = field_line(cb, "Level")
                if lvl not in LEVELS:
                    r.err(p.rel, f"{c.group(1)} Level `{lvl}` not in {sorted(LEVELS)}")
                for kw in ("GIVEN", "WHEN", "THEN"):
                    if f"**{kw}**" not in cb:
                        r.err(p.rel, f"{c.group(1)} lacks **{kw}**")
                if cb.count("**WHEN**") > 1:
                    r.err(p.rel, f"{c.group(1)} has more than one WHEN")
                for line in re.findall(r"\*\*(?:THEN|AND)\*\*(.+)", cb):
                    if VAGUE.search(line):
                        r.warn(p.rel, f"{c.group(1)} THEN uses a vague word: {VAGUE.search(line).group(0)}")
            for ref in re.split(r"[,;] *", field_line(block, "Source")):
                ref = ref.strip()
                if not ref:
                    continue
                base = ref.split("@")[0].split(" ")[0]
                if base.startswith(("F-", "UC-", "SCR-", "FLW-")) and "@" not in ref:
                    r.err(p.rel, f"{rid} Source `{ref}` has no definition version (rev 9 P60)")
                if known_ext is not None and ID_REF.fullmatch(base) and base not in known_ext:
                    r.err(p.rel, f"{rid} Source `{base}` does not resolve")

    # definition: features in families, use cases exercise every effective criterion
    if kind == "definition":
        served: set[str] = set()
        for p in pages:
            if p.rel.startswith("use-cases/") and p.meta.get("type") == "design":
                serves = field_line(strip_generated(p.body), "Serves")
                for fid, acs in re.findall(r"(F-\d+(?:\.CR-\d+)?) *\(([^)]*)\)", serves):
                    base = fid.split(".")[0]
                    for ac in re.findall(r"AC-\d+", acs):
                        served.add(f"{base}.{ac}")
        for p in pages:
            if p.meta.get("type") != "feature":
                continue
            parts = p.rel.split("/")
            if len(parts) != 3 or parts[0] != "features":
                r.err(p.rel, "a feature must live in features/<family>/")
            acs, sup = acceptance_criteria(p)
            if not acs:
                r.err(p.rel, "feature has no acceptance criteria")
            for ac in acs:
                if ac not in sup and ac not in served:
                    r.err(p.rel, f"{ac} is not exercised by any use case (P63)")
            for cr in re.findall(r"^## (F-\d+\.CR-\d+)", strip_generated(p.body), re.M):
                sec = section(strip_generated(p.body), f"## {cr}")
                if "revision" in field_line(sec, "Kind") and "**Supersedes.** F-" not in sec:
                    r.err(p.rel, f"{cr} is a revision but names nothing it supersedes")
        # versions match the change log
        changes = by_id.get("META.3")
        if changes:
            rows = re.findall(r"^\| *(\d{4}) *\| *[\d-]+ *\| *(\w+) *\| *(\d+\.\d+\.\d+) *\|", changes.body, re.M)
            for scheme, fname in (("definition", "DEFINITION_VERSION"), ("spec", "SPEC_VERSION")):
                newest = next((v for _, s, v in rows if s == scheme), None)
                actual = (ROOT / fname).read_text().strip() if (ROOT / fname).exists() else None
                if newest != actual:
                    r.err(fname, f"{actual} != newest {scheme} row in meta/changes.md ({newest})")

    # implementation: Where pointers still exist in the code (sio docs check, P56)
    if kind == "implementation" and code_root:
        for p in pages:
            for rid, path, syms in where_rows(p):
                f = code_root / path
                if not f.exists():
                    r.err(p.rel, f"Where: {path} does not exist in {code_root}")
                    continue
                src = f.read_text(errors="ignore")
                for s in syms:
                    name = s.split("(")[0].split(".")[-1]  # `Type.member(_:)` -> `member`
                    if name and name not in src:
                        r.err(p.rel, f"Where: symbol `{s}` not found in {path}")

    # generated blocks are current
    for path in regenerate(pages):
        r.err(path.relative_to(DOCS).as_posix(), "generated sections are stale: run `sitegen.py generate`")
    return r


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("command", choices=["nav", "generate", "check"])
    ap.add_argument("--site", choices=["definition", "implementation"])
    ap.add_argument("--code-root", type=Path)
    args = ap.parse_args()
    pages = load_pages()
    if args.command == "generate":
        for path, text in regenerate(pages).items():
            path.write_text(text)
            print(f"generated {path.relative_to(ROOT)}")
    elif args.command == "nav":
        write_nav(pages)
        print(f"wrote nav for {len(pages)} pages to mkdocs.yml")
    else:
        r = check(pages, site_kind(args), args.code_root)
        for w in r.warnings:
            print(f"warning: {w}")
        for e in r.errors:
            print(f"error: {e}")
        print(f"{len(pages)} pages · {len(r.errors)} errors · {len(r.warnings)} warnings")
        sys.exit(1 if r.errors else 0)


